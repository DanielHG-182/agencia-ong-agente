def run_monitored_pipeline(
    question: str,
    chroma_dir: str,
    directives_path: Path | None,
) -> dict:
    """
    Runs the real RAG pipeline (retrieve → generate_draft) for a single
    question and captures timing + error telemetry.
    """
    
    run_log = {
        "status": "success",
        "error_message": None,
        "failed_stage": None,
        "retrieval_time_sec": 0.0,
        "generation_time_sec": 0.0,
        "total_pipeline_time_sec": 0.0,
        "contexts": [],
        "retrieved_chunks": [],
        "answer": "",
    }

    start_total = time.time()

    # ── RETRIEVAL ──────────────────────────────────────────
    try:
        start = time.time()
        raw_chunks = retrieve(query=question, chroma_dir=chroma_dir)

        run_log["contexts"] = ensure_string_contexts(raw_chunks)

        run_log["retrieved_chunks"] = [
            {
                "chunk_id": chunk.chunk_id,
                "source_file": chunk.source_file,
                "section_title": chunk.section_title,
                "section_level": chunk.section_level,
                "parent_section": chunk.parent_section,
                "is_continuation": chunk.is_continuation,
                "has_table": chunk.has_table,
                "relevance_score": chunk.relevance_score,
                "content": chunk.content,
            }
            for chunk in raw_chunks
        ]

        run_log["retrieval_time_sec"] = round(time.time() - start, 3)

    except Exception as e:
        run_log.update(status="failed", failed_stage="retrieval", error_message=str(e))
        run_log["total_pipeline_time_sec"] = round(time.time() - start_total, 3)
        return run_log

    # ── GENERATION ────────────────────────────────────────
    try:
        start = time.time()

        result = generate_draft(
            section_name=EVAL_SECTION_NAME,
            user_instruction=question,
            directives_path=directives_path,
            chroma_dir=chroma_dir,
            retrieval_query=question,
            mode="evaluation",
            retrieved_chunks=raw_chunks,
        )

        # generate_draft returns a DraftResult; extract text content
        run_log["answer"] = (
            result.content if hasattr(result, "content") else str(result)
        )
        run_log["generation_time_sec"] = round(time.time() - start, 3)

    except Exception as e:
        run_log.update(status="failed", failed_stage="generation", error_message=str(e))
        run_log["total_pipeline_time_sec"] = round(time.time() - start_total, 3)
        return run_log

    run_log["total_pipeline_time_sec"] = round(time.time() - start_total, 3)
    return run_log


# ─────────────────────────────────────────────────────────
# MAIN  (callable from main.py as main(project_name) or standalone)
