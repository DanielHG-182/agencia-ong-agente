def load_golden_dataset(json_path: Path) -> list[dict]:
    """
    Loads the synthetic golden dataset produced by
    scripts/generate_synthetic_dataset.py.

    Supports two JSON structures:

    1. Flat list:
       [
           {"eval_id": "FACT_001", "category": "factual",
            "question": "...", "ground_truth": "...", ...},
           ...
       ]

    2. Wrapped object (legacy / alternative format):
       {
           "project": "...",
           "items": [
               {"eval_id": "FACT_001", "category": "factual",
                "question": "...", "ground_truth": "...", ...},
               ...
           ]
       }

    Required fields per item: eval_id, category, answerable, question, ground_truth.
    Optional fields preserved in telemetry:
    source, source_chunk_id, source_chunk_ids,source_section, source_sections.
    """
    if not json_path.exists():
        print(f"[ERROR] Golden dataset not found: {json_path}")
        print(
            "Run first: "
            "python main.py --stage eval-generate --project <name>"
        )
        sys.exit(1)

    with open(json_path, encoding="utf-8") as f:
        raw = json.load(f)

    # Normalise to a flat list regardless of input shape
    if isinstance(raw, list):
        items = raw
    elif isinstance(raw, dict):
        items = raw.get("items", [])
    else:
        print(f"[ERROR] Unexpected JSON structure in: {json_path}")
        sys.exit(1)

    if not items:
        print(f"[ERROR] Golden dataset is empty: {json_path}")
        sys.exit(1)

    # Validate required fields
    required = {
        "eval_id",
        "category",
        "answerable",
        "question",
        "ground_truth",
    }
    invalid = []
    for i, item in enumerate(items):
        missing = required - item.keys()
        if missing:
            print(f"[WARN] Item {i} missing fields {missing} — skipping.")
            invalid.append(i)

    valid = [item for i, item in enumerate(items) if i not in invalid]
    print(f"[INFO] Loaded {len(valid)} valid items from {json_path.name}")
    return valid


